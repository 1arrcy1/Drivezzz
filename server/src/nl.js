export function toDutch(text) {
  if (typeof text !== 'string' || !text) return text;
  if (Object.hasOwn(EXACT, text)) return EXACT[text];
  for (const { re, nl } of PATTERNS) {
    const m = re.exec(text);
    if (!m) continue;
    return nl.replace(/\{(\d+)(?::(t|list|num))?\}/g, (_, i, how) => {
      const part = m[Number(i)] ?? '';
      if (how === 't') return toDutch(part);
      if (how === 'list') return part.split(', ').map(toDutch).join(', ');
      if (how === 'num') return part.replace(/(\d)\.(\d)/g, '$1,$2');
      return part;
    });
  }
  return text;
}

